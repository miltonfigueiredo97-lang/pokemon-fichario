// Builds supabase/functions/api from the Vercel handlers in api/, so the light
// endpoints (catalog, set lists, images) run on Supabase Edge Functions when
// the site is served as static files (GitHub Pages).
//
//   node scripts/build-supabase-api.mjs
//
// Each CommonJS handler is wrapped as an ES module with a small require() map.
// Image handlers never send image bytes to the browser (Supabase egress is
// limited on the free plan): their upstream fetch is checked as usual, then the
// browser is redirected (302) to the image's own URL.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'supabase/functions/api');

const JSON_HANDLERS = ['set-catalog', 'master-set', 'legacy-card-search', 'jp-card-search', 'limitless-variants', 'card-image-fallback'];
const IMAGE_HANDLERS = ['image-proxy', 'tcgdex-card-image', 'jp-card-image', 'limitless-image', 'poketrack-image'];
// They open Chromium: served by the local reader, not by Supabase.
const BROWSER_HANDLERS = ['myp-search', 'myp-catalog-public', 'myp-related-catalog', 'mypcards-public', 'mypcards', 'liga-public', 'price-engine'];

function wrapCommonJs(source, requires) {
  const map = Object.entries(requires).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join('\n');
  return `// Generated by scripts/build-supabase-api.mjs. Do not edit.
import { Buffer } from "node:buffer";
${Object.values(requires).filter((v) => /^__dep_/.test(v)).map((v) => `import ${v} from "./${v.slice(6).replace(/_/g, '-')}.js";`).join('\n')}
const module = { exports: {} };
const exports = module.exports;
const __requires = {
${map}
};
function require(name) {
  if (!(name in __requires)) throw new Error("require not bundled: " + name);
  return __requires[name];
}
${source}
export default module.exports;
`;
}

fs.rmSync(path.join(out, 'handlers'), { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'handlers'), { recursive: true });

// lib/jp-official.js (used by the JP handlers) and the JP set labels.
fs.writeFileSync(path.join(out, 'handlers/jp-official.js'), wrapCommonJs(fs.readFileSync(path.join(root, 'lib/jp-official.js'), 'utf8'), {}));
fs.writeFileSync(path.join(out, 'handlers/jp-set-labels.js'),
  '// Generated by scripts/build-supabase-api.mjs. Do not edit.\nexport default ' + fs.readFileSync(path.join(root, 'data/jp-set-labels.json'), 'utf8').trim() + ';\n');

const deps = { '../lib/jp-official': '__dep_jp_official', '../data/jp-set-labels.json': '__dep_jp_set_labels' };
for (const name of [...JSON_HANDLERS, ...IMAGE_HANDLERS]) {
  let src = fs.readFileSync(path.join(root, 'api', name + '.js'), 'utf8');
  const used = Object.fromEntries(Object.entries(deps).filter(([k]) => src.includes(k)));
  if (IMAGE_HANDLERS.includes(name)) src = 'const fetch = (...a) => globalThis.__imageAwareFetch(...a);\n' + src;
  fs.writeFileSync(path.join(out, 'handlers', name + '.js'), wrapCommonJs(src, used));
}

const imports = [...JSON_HANDLERS, ...IMAGE_HANDLERS].map((n) => `import h_${n.replace(/-/g, '_')} from "./${n}.js";`).join('\n');
const table = [...JSON_HANDLERS, ...IMAGE_HANDLERS].map((n) => `  ${JSON.stringify(n)}: h_${n.replace(/-/g, '_')},`).join('\n');
fs.writeFileSync(path.join(out, 'handlers/index.js'), `// Generated by scripts/build-supabase-api.mjs. Do not edit.
${imports}
export const HANDLERS = {
${table}
};
export const IMAGE_HANDLERS = new Set(${JSON.stringify(IMAGE_HANDLERS)});
export const BROWSER_HANDLERS = new Set(${JSON.stringify(BROWSER_HANDLERS)});
`);
console.log('built', JSON_HANDLERS.length + IMAGE_HANDLERS.length, 'handlers into', path.relative(root, out));
